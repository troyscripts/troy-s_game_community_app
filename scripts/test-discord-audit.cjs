'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {EventEmitter}=require('node:events');
const {PermissionsBitField,PermissionFlagsBits:P,Events}=require('discord.js');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'audit-'));
const defaults=require('../config/defaults');defaults.Database.File=path.join(temp,'test.sqlite');defaults.Logging.Files=false;
const database=require('../database/database');database.initializeDatabase();
const settings=require('../database/guildSettings');settings.initialize();
const config=require('../config/config');
const audit=require('../services/discordAudit');
const g='111111111111111111',h='222222222222222222',main='333333333333333333',special='444444444444444444';
const client=new EventEmitter();client.user={id:'bot'};client.guilds={cache:new Map()};
let fail=false,allowed=true,sent=[];
const guild=id=>({id,members:{me:{id:'bot'}},channels:{fetch:async target=>({id:target,guild:{id},isTextBased:()=>true,permissionsFor:()=>new PermissionsBitField(allowed?[P.ViewChannel,P.SendMessages,P.EmbedLinks]:[]),send:async payload=>{if(fail)throw Error('network failed');sent.push({guild:id,target,payload});}})}});
const one=guild(g),two=guild(h);client.guilds.cache.set(g,one);client.guilds.cache.set(h,two);
async function run(){
 settings.ensureGuild(g);settings.ensureGuild(h);
 settings.updateValue(g,'Logging.Channel',main);
 settings.updateValue(g,'Logging.Channels.Voice',`<#${special}>`);
 assert.equal(settings.getGuildConfig(g).Logging.Channels.Voice,special);
 assert.equal(settings.getGuildConfig(h).Logging.Channels.Voice,'');
 assert.throws(()=>settings.updateValue(g,'Logging.Channels.Voice','bad'));
 assert.throws(()=>settings.updateValue(g,'Logging.QueueLimit','-1'));
 assert.equal(audit.enqueue(two,'Voice','Not configured'),null);
 audit.install(client);audit.install(client);assert.equal(client.listenerCount(Events.MessageCreate),1);
 const base={id:'m',guild:one,author:{id:'user',tag:'tester'},channelId:'c',content:'@everyone hello',attachments:new Map()};
 client.emit(Events.MessageCreate,base);client.emit(Events.MessageCreate,{...base,author:{id:'bot'}});
 assert.equal(audit.status(g)[0].count,1);
 await audit.drain(client);assert.equal(sent.length,1);assert.equal(sent[0].target,main);assert.deepEqual(sent[0].payload.allowedMentions.parse,[]);
 assert.ok(sent[0].payload.nonce);assert.equal(sent[0].payload.enforceNonce,true);
 client.emit(Events.VoiceStateUpdate,{channelId:null},{id:'user',guild:one,channelId:'v'});
 await audit.drain(client);assert.equal(sent[1].target,special);
 settings.updateValue(g,'Logging.Events.Messages','nee');client.emit(Events.MessageCreate,base);assert.equal(audit.status(g).reduce((n,r)=>n+r.count,0),2);
 fail=true;const bad=audit.enqueue(one,'Voice','Retry');await audit.drain(client);
 assert.equal(database.db.prepare('SELECT attempts FROM discord_event_logs WHERE id=?').get(bad).attempts,1);
 fail=false;settings.updateValue(g,'Logging.Channels.Voice',main);
 database.db.prepare('UPDATE discord_event_logs SET next_attempt=0 WHERE id=?').run(bad);
 await audit.drain(client);assert.equal(sent.at(-1).target,main,'Queued logs follow corrected config');
 allowed=false;const denied=audit.enqueue(one,'Audit','Denied');
 for(let x=0;x<5;x++){database.db.prepare('UPDATE discord_event_logs SET next_attempt=0 WHERE id=?').run(denied);await audit.drain(client);}
 assert.equal(database.db.prepare('SELECT status FROM discord_event_logs WHERE id=?').get(denied).status,'failed');
 assert.equal(audit.retry(h),0);assert.equal(audit.retry(g),1);allowed=true;await audit.drain(client);
 settings.updateValue(g,'Logging.Events.Audit','nee');assert.equal(audit.enqueue(one,'Audit','off'),null);
 client.emit(Events.GuildRoleCreate,{id:'role',name:'test',guild:one,permissions:new PermissionsBitField()});
 assert.ok(database.db.prepare("SELECT id FROM discord_event_logs WHERE guild_id=? AND category='Roles'").get(g));
 await audit.drain(client);
 client.emit(Events.GuildAuditLogEntryCreate,{id:'audit',action:20,executorId:'staff',targetId:'user',changes:[{key:'token',new:'SECRET'}]},one);
 const moderation=database.db.prepare("SELECT payload FROM discord_event_logs WHERE guild_id=? AND category='Moderation' ORDER BY id DESC").get(g);
 assert.ok(moderation);assert.equal(moderation.payload.includes('SECRET'),false);await audit.drain(client);
 const originalCount=sent.length;settings.updateValue(h,'Logging.Channel',special);audit.enqueue(two,'Messages','Other guild');await audit.drain(client);assert.equal(sent.length,originalCount+1);assert.equal(sent.at(-1).guild,h);
 const envelope=audit.envelope('t'.repeat(1000),'d'.repeat(10000),Array.from({length:30},()=>({name:'n',value:'v'.repeat(2000)})));
 const e=envelope.embeds[0];assert.ok(e.title.length+e.description.length+e.fields.reduce((n,f)=>n+f.name.length+f.value.length,0)<=5400);
 settings.updateValue(g,'Logging.QueueLimit','10');for(let x=0;x<11;x++)audit.enqueue(one,'Voice','load');
 assert.ok(audit.status(g).some(r=>r.status==='failed'));
 delete require.cache[require.resolve('../services/discordAudit')];assert.ok(require('../services/discordAudit').status(g).some(r=>r.status==='pending'));
 // Old rows are removed on the next enqueue; default per-server retention is bounded.
 database.db.prepare('UPDATE discord_event_logs SET created_at=0 WHERE guild_id=?').run(g);audit.enqueue(one,'Voice','new');assert.equal(audit.status(g).reduce((n,r)=>n+r.count,0),1);
 console.log('PASS Discord logging: routing, server isolation, config validation, event registration, no self-loop/pings, queue retry/persistence/limits, rights, retention and embed limits.');
}
run().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{audit.stop();database.closeDatabase();fs.rmSync(temp,{recursive:true,force:true});});
